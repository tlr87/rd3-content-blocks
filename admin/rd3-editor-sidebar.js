(function () {

    'use strict';


    /*
     * =========================================================
     * RD3 EDITOR SIDEBAR
     * =========================================================
     *
     * Handles:
     *
     * - Content Block insertion
     * - Row insertion
     * - Advanced Row insertion
     * - Editing selected items
     * - Classic Editor / TinyMCE
     * - Text / HTML editor
     *
     */


    /*
     * =========================================================
     * INSERT SHORTCODE
     * =========================================================
     */

    window.rd3_content_blocks_insert_shortcode = function (shortcode) {


        /*
         * -----------------------------------------------------
         * TINYMCE / VISUAL EDITOR
         * -----------------------------------------------------
         */

        if (
            typeof tinymce !== 'undefined'
        ) {

            var editor =
                tinymce.get('content');


            if (editor) {

                editor.focus();


                /*
                 * Insert shortcode at the current cursor.
                 */

                editor.insertContent(
                    shortcode
                );


                /*
                 * Notify WordPress that the editor changed.
                 */

                editor.fire('change');


                return true;
            }
        }


        /*
         * -----------------------------------------------------
         * TEXT / HTML EDITOR
         * -----------------------------------------------------
         */

        var textarea =
            document.getElementById('content');


        if (textarea) {

            var start =
                typeof textarea.selectionStart === 'number'
                    ? textarea.selectionStart
                    : textarea.value.length;


            var end =
                typeof textarea.selectionEnd === 'number'
                    ? textarea.selectionEnd
                    : textarea.value.length;


            /*
             * Insert shortcode at the current cursor.
             */

            textarea.value =
                textarea.value.substring(
                    0,
                    start
                )
                +
                shortcode
                +
                textarea.value.substring(
                    end
                );


            /*
             * Notify WordPress that the textarea changed.
             */

            textarea.dispatchEvent(
                new Event(
                    'input',
                    {
                        bubbles: true
                    }
                )
            );


            textarea.dispatchEvent(
                new Event(
                    'change',
                    {
                        bubbles: true
                    }
                )
            );


            return true;
        }


        /*
         * No editor was found.
         *
         * Keep this error because it indicates a genuine
         * problem rather than normal diagnostic output.
         */

        console.error(
            'RD3: NO EDITOR FOUND'
        );


        return false;
    };


    /*
     * =========================================================
     * ADD TO POST
     * =========================================================
     *
     * Event delegation is used so the buttons continue to
     * work if WordPress changes/rebuilds editor UI.
     */

    document.addEventListener(
        'click',
        function (event) {


            var button =
                event.target.closest(
                    '.rd3-add-to-post'
                );


            if (!button) {
                return;
            }


            event.preventDefault();


            /*
             * Find the select belonging to this button.
             */

            var selectId =
                button.getAttribute(
                    'data-select'
                );


            if (!selectId) {
                return;
            }


            var select =
                document.getElementById(
                    selectId
                );


            if (
                !select ||
                !select.value
            ) {
                return;
            }


            /*
             * Get selected option.
             */

            var option =
                select.options[
                    select.selectedIndex
                ];


            if (!option) {
                return;
            }


            /*
             * Get shortcode.

             * The shortcode is generated by PHP and stored
             * in the option's data-shortcode attribute.
             */

            var shortcode =
                option.getAttribute(
                    'data-shortcode'
                );


            if (!shortcode) {
                return;
            }


            /*
             * Insert shortcode.
             */

            window.rd3_content_blocks_insert_shortcode(
                shortcode
            );


        },
        false
    );


    /*
     * =========================================================
     * EDIT SELECTED ITEM
     * =========================================================
     *
     * Opens the selected Content Block, Row or Advanced Row
     * in a new browser tab.
     *
     * The current Post/Page editor remains open.
     */

    document.addEventListener(
        'click',
        function (event) {


            var button =
                event.target.closest(
                    '.rd3-edit-selected'
                );


            if (!button) {
                return;
            }


            event.preventDefault();


            /*
             * Find the select belonging to this button.
             */

            var selectId =
                button.getAttribute(
                    'data-select'
                );


            if (!selectId) {
                return;
            }


            var select =
                document.getElementById(
                    selectId
                );


            if (
                !select ||
                !select.value
            ) {
                return;
            }


            /*
             * Get selected option.
             */

            var option =
                select.options[
                    select.selectedIndex
                ];


            if (!option) {
                return;
            }


            /*
             * Get edit URL.
             */

            var editUrl =
                option.getAttribute(
                    'data-edit-url'
                );


            if (!editUrl) {
                return;
            }


            /*
             * Open the RD3 item in a new tab.
             */

            window.open(
                editUrl,
                '_blank'
            );


        },
        false
    );


    /*
     * =========================================================
     * ENABLE / DISABLE EDIT BUTTON
     * =========================================================
     */

    document.addEventListener(
        'change',
        function (event) {


            var select =
                event.target.closest(
                    '.rd3-editor-sidebar-select'
                );


            if (!select) {
                return;
            }


            var section =
                select.closest(
                    '.rd3-editor-sidebar-section'
                );


            if (!section) {
                return;
            }


            var editButton =
                section.querySelector(
                    '.rd3-edit-selected'
                );


            if (editButton) {

                editButton.disabled =
                    !select.value;

            }


        },
        false
    );


    /*
     * =========================================================
     * RD3 DEBUG / TESTS
     * =========================================================
     *
     * The tests below are intentionally commented out.
     *
     * If the sidebar breaks in the future, uncomment the
     * relevant test, reload the Post/Page editor, and run
     * the test in the browser console.
     *
     */


    /*
     * ---------------------------------------------------------
     * TEST 1 — Check that the insert function exists.
     *
     * Expected result:
     *
     * "function"
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — insert function:',
     *     typeof window.rd3_content_blocks_insert_shortcode
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 2 — Manually insert a known Content Block.
     *
     * Replace 2532 with another Content Block ID if required.
     *
     * Expected result:
     *
     * true
     *
     * ---------------------------------------------------------
     *
     * window.rd3_content_blocks_insert_shortcode(
     *     '[rd3_block id="2532"]'
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 3 — Check Text / HTML editor content.
     *
     * Expected result:
     *
     * The shortcode currently inside #content.
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — textarea content:',
     *     document.getElementById('content')
     *         ? document.getElementById('content').value
     *         : 'textarea not found'
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 4 — Check TinyMCE content.
     *
     * Expected result:
     *
     * HTML containing the shortcode.
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — TinyMCE content:',
     *     typeof tinymce !== 'undefined' &&
     *     tinymce.get('content')
     *         ? tinymce.get('content').getContent()
     *         : 'TinyMCE editor not found'
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 5 — Check that this JavaScript file is loaded.
     *
     * Expected result:
     *
     * A <script> element for rd3-editor-sidebar.js.
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — sidebar script:',
     *     document.querySelector(
     *         'script[src*="rd3-editor-sidebar"]'
     *     )
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 6 — Count Add to Post buttons.
     *
     * Expected result:
     *
     * 3
     *
     * for Content Block, Row and Advanced Row.
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — Add to Post buttons:',
     *     document.querySelectorAll(
     *         '.rd3-add-to-post'
     *     ).length
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 7 — Check the Content Block selector.
     *
     * Expected result:
     *
     * The #rd3-content-block-select element.
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — Content Block selector:',
     *     document.getElementById(
     *         'rd3-content-block-select'
     *     )
     * );
     */


    /*
     * ---------------------------------------------------------
     * TEST 8 — Check all RD3 selectors.
     *
     * Expected result:
     *
     * 3
     *
     * ---------------------------------------------------------
     *
     * console.log(
     *     'RD3 TEST — RD3 selectors:',
     *     document.querySelectorAll(
     *         '.rd3-editor-sidebar-select'
     *     ).length
     * );
     */


})();